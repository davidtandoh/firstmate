import json, os, pathlib, subprocess, tempfile, time
root = pathlib.Path.cwd()
with tempfile.TemporaryDirectory(prefix='.retention-live-', dir=root) as temp:
    home = pathlib.Path(temp)
    for p in ('data/demo/cache', 'data/legacy', 'state', 'config', 'user', 'slot/repo/node_modules'):
        (home / p).mkdir(parents=True, exist_ok=True)
    (home / '.tasks.toml').write_text('backend = "markdown"\n[markdown]\npath = "data/backlog.md"\ndone_keep = 100\n')
    (home / 'data/backlog.md').write_text('# Backlog\n\n## In flight\n\n## Queued\n\n## Done\n')
    (home / 'data/demo/report.md').write_text('Deliverable retained\n')
    (home / 'data/demo/cache/render.bin').write_bytes(b'x'*4096)
    (home / 'data/legacy/old-render.bin').write_bytes(b'y'*1024)
    (home / 'slot/repo/node_modules/cache.bin').write_bytes(b'z'*128)
    env = dict(os.environ, HOME=str(home/'user'), FM_HOME=str(home))
    for name in ('FM_ROOT_OVERRIDE','FM_STATE_OVERRIDE','FM_DATA_OVERRIDE','FM_CONFIG_OVERRIDE','TASKS_AXI_FILE','TASKS_AXI_BACKEND'):
        env.pop(name, None)
    def run(command):
        p = subprocess.run(command, cwd=home, env=env, text=True, capture_output=True, timeout=120)
        print('$ ' + ' '.join(command), flush=True)
        print(p.stdout, end='', flush=True)
        if p.stderr: print(p.stderr, end='', flush=True)
        print('exit=' + str(p.returncode), flush=True)
        assert p.returncode == 0
        return p.stdout
    def cli(*args): return run(['bash', str(root/'bin/fm-task-retention.sh'), *args])
    run(['tasks-axi','add','demo','Completed render'])
    cli('declare','demo','--scratch','cache','--worktree-cache','node_modules')
    cli('report')
    run(['tasks-axi','done','demo','--report','data/demo/report.md'])
    cli('complete','demo','--artifact','report.md','--worktree',str(home/'slot/repo'),'--lease-released')
    cli('report')
    receipt = home/'data/demo/retention-complete.json'
    value = json.loads(receipt.read_text()); value['completed_at'] = int(time.time()) - 8*86400
    receipt.write_text(json.dumps(value))
    print('Fixture clock advanced beyond seven-day grace period', flush=True)
    cli('report','--prune')
    assert (home/'data/demo/cache/render.bin').exists()
    print('Confirmed: --prune alone preserved scratch under default report mode', flush=True)
    (home/'config/task-retention').write_text('prune\n')
    (home/'state/demo.meta').write_text('window=fixture\n')
    cli('report','--prune')
    assert (home/'data/demo/cache/render.bin').exists()
    (home/'state/demo.meta').unlink()
    run(['tasks-axi','add','decision','Review demo evidence'])
    run(['tasks-axi','hold','decision','--kind','captain','--reason','Review data/demo/cache'])
    cli('report','--prune')
    assert (home/'data/demo/cache/render.bin').exists()
    run(['tasks-axi','done','decision'])
    link=home/'data/demo/cache/link'
    link.symlink_to(home/'user',target_is_directory=True)
    cli('report','--prune')
    assert (home/'data/demo/cache/render.bin').exists()
    link.unlink()
    declaration=home/'data/demo/scratch.json'
    original=declaration.read_bytes()
    changed=json.loads(original); changed['scratch'].append('extra')
    declaration.write_text(json.dumps(changed))
    cli('report','--prune')
    assert (home/'data/demo/cache/render.bin').exists()
    declaration.write_bytes(original)
    print('Confirmed: endpoint, open hold, symlink, and changed declaration each blocked pruning',flush=True)
    cli('report','--prune','--dry-run')
    assert (home/'data/demo/cache/render.bin').exists()
    cli('report','--prune')
    assert not (home/'data/demo/cache/render.bin').exists()
    for path in ('data/demo/report.md','data/legacy/old-render.bin','slot/repo/node_modules/cache.bin'):
        assert (home/path).exists()
    print('Confirmed: only declared scratch removed; deliverable, legacy data, and worktree cache preserved', flush=True)
    print('Removal audit: ' + (home/'data/demo/retention-removals.jsonl').read_text(), flush=True)
    cli('tick')
    first = (home/'state/task-retention-report.json').read_bytes()
    wake = (home/'state/.wake-queue').read_bytes()
    cli('tick')
    assert first == (home/'state/task-retention-report.json').read_bytes()
    assert wake == (home/'state/.wake-queue').read_bytes()
    print('Confirmed: weekly report and wake published once; repeated tick made no additional publication', flush=True)
